"""Pack the original Thorn Crown camera and shaft loops for the native editor.
Usage: python bake_thorn.py CAMERA.mp4 SHAFT.mp4 MOTION_ASSETS.json
Requires Pillow and ffmpeg. Normal plug-in builds use the committed bank.
"""
import base64
import io
import json
from pathlib import Path
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "mac-clap/assets/thorn"
frames = []


def store(image):
    out = io.BytesIO()
    image.save(out, format="PNG", optimize=True)
    frames.append(out.getvalue())


def movie(path, width, fps):
    start = len(frames)
    with tempfile.TemporaryDirectory() as temp:
        subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-vf", f"fps={fps},scale={width}:-2",
                        "-q:v", "5", "-pix_fmt", "yuvj444p", f"{temp}/%04d.jpg"], check=True)
        frames.extend(p.read_bytes() for p in sorted(Path(temp).glob("*.jpg")))
    return start, len(frames) - start


def font_sheet(filename, density=1):
    font = ImageFont.truetype(str(ROOT / "assets/fonts" / filename), 40*density)
    atlas = Image.new("L", (16*56*density, 6*56*density))
    draw = ImageDraw.Draw(atlas)
    widths = []
    for index in range(96):
        char = chr(index+32)
        draw.text(((index%16*56+4)*density, (index//16*56+4)*density), char, font=font, fill=255, anchor="la")
        widths.append(round(font.getlength(char)*16))
    store(atlas)
    return widths


def sprite(uri):
    return Image.open(io.BytesIO(base64.b64decode(uri.split(",", 1)[1]))).convert("RGBA")


def silver_face(image):
    ramp = [(0,(10,8,27)),(.2,(29,27,60)),(.43,(42,62,122)),(.61,(75,107,194)),
            (.78,(141,170,227)),(.91,(208,223,249)),(1,(246,247,255))]
    for y in range(image.height):
        for x in range(image.width):
            red,green,blue,alpha = image.getpixel((x,y))
            if not alpha:
                continue
            r,g,b = red/255, green/255, blue/255
            t = max(r*.85,g,b*.85)
            split = min(1,max(0,((x%68)/67*.74+y/67*.52-.46)*1.95))
            mix = min(1,max(0,(g-max(r*.70,b))/.37))
            k = next(i for i in range(1,len(ramp)) if ramp[i][0]>=t)
            lo,hi = ramp[k-1],ramp[k]
            u=(t-lo[0])/(hi[0]-lo[0])
            lum=r*.29+g*.54+b*.17
            rgb=[]
            for i in range(3):
                enamel=((92,171,255)[i]*(1-split)+(181,129,255)[i]*split)*(.48+.52*t)
                cold=.24*(lo[1][i]+(hi[1][i]-lo[1][i])*u)+.76*enamel
                metal=(.90,.97,1.12)[i]*lum*238+(6,5,17)[i]+(18,2,30)[i]*y/67*max(0,1-1.8*lum)
                rgb.append(min(255,max(0,round(metal*(1-mix)+cold*mix))))
            image.putpixel((x,y), (*rgb,alpha))
    return image


camera, shaft, source = sys.argv[1:]
assets = json.loads(Path(source).read_text())
store(sprite(assets["logo"]))
store(silver_face(sprite(assets["face"])))
fonts = ("Barlow-SemiBold.ttf", "BarlowCondensed-BoldItalic.ttf")
widths = [font_sheet(f) for f in fonts]
for f in fonts:
    font_sheet(f, 2)
store(Image.open(ROOT / "assets/art/satin-knob.png").convert("RGBA"))
camera_start, camera_count = movie(camera, 528, 20)
shaft_start, shaft_count = movie(shaft, 320, 24)
offsets = [0]
for data in frames:
    offsets.append(offsets[-1]+len(data))
(DEST/"panel.bank").write_bytes(b"".join(frames))
def array(name, kind, values):
    return f"inline constexpr {kind} {name}[] = {{\n" + "".join(
        "    "+", ".join(map(str,values[i:i+12]))+",\n" for i in range(0,len(values),12))+"};\n"
(DEST/"index.h").write_text("// Generated by tools/bake_thorn.py.\n#pragma once\n#include <cstdint>\nnamespace thorn {\n"
    + f"constexpr int cameraFirst={camera_start}, cameraCount={camera_count}, shaftFirst={shaft_start}, shaftCount={shaft_count};\n"
    + array("offset","uint32_t",offsets)+array("regularAdvance","uint16_t",widths[0])
    + array("italicAdvance","uint16_t",widths[1])+"}\n")
