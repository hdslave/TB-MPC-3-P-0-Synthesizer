"""Pack the native-scale Null Port artwork for the freesp16 framebuffer (Pillow).

Each group starts on a fresh row in the master PNG. Frames read left to right,
wrapping at the right edge. All colors, including partial coverage, survive
packing. Ordinary plug-in builds use the checked-in bank.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'assets/sp16-thorn'
MASTER = ROOT / 'tools/sp16_thorn/media/null-port.png'
GROUPS = [
    ('lane', 60, 144, 1), ('stepTitle', 32, 12, 1), ('seedTitle', 32, 13, 1),
    ('regen', 53, 26, 1), ('transport', 81, 29, 4), ('stepNumber', 42, 20, 32),
    ('counter', 92, 70, 32), ('length', 21, 13, 32), ('hexDigit', 11, 22, 16),
    ('tab', 77, 33, 12), ('scaleKey', 115, 33, 1), ('root', 17, 20, 12),
    ('slash', 6, 20, 1), ('scaleName', 77, 20, 128), ('stormRim', 168, 33, 1),
    ('noteKey', 42, 33, 2), ('accentMark', 31, 15, 4), ('slideMark', 31, 16, 4),
]


def pack():
    master = Image.open(MASTER).convert('RGBA')
    header = ['// Generated by tools/sp16_thorn/pack_controls.py', '#pragma once',
              'namespace tbmpc::sp16::controls {',
              'struct Tiles { unsigned offset; int w, h, count; };']
    pixels = bytearray()
    y = 0
    for name, width, height, count in GROUPS:
        per_row = master.width // width
        header.append(f'inline constexpr Tiles {name} {{{len(pixels)//4}, {width}, {height}, {count}}};')
        for i in range(count):
            x = i % per_row * width
            top = y + i // per_row * height
            pixels.extend(master.crop((x, top, x+width, top+height)).tobytes('raw', 'BGRA'))
        y += (count + per_row - 1) // per_row * height
    if y != master.height:
        raise ValueError('Sprite layout and artwork height disagree')
    (DEST / 'controls.h').write_text('\n'.join(header + ['}']) + '\n')
    (DEST / 'controls.bank').write_bytes(pixels)


if __name__ == '__main__':
    pack()
