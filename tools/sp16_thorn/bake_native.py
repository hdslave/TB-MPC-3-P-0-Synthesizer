"""Bake the SP-16 UI plates from the same vector lettering and motion study.

Requires Pillow and Playwright with a WebGL-capable Chromium. The plug-in links the
built bank directly. Its UI thread only expands the affected rectangles.
"""
import argparse
import base64
import io
from pathlib import Path
import re
import struct
import tempfile

from PIL import Image, ImageDraw
from playwright.sync_api import sync_playwright
from build import ROOT, SOURCE, build_fragment

DEST = ROOT / 'assets/sp16-thorn'
RUNS = re.compile(rb'(.)\1{2,}', re.DOTALL)


def pack_row(row):
    result = bytearray()
    start = 0
    for match in RUNS.finditer(row):
        for i in range(start, match.start(), 128):
            run = row[i:min(i+128, match.start())]
            result.append(len(run)-1)
            result.extend(run)
        for i in range(match.start(), match.end(), 128):
            result.extend((127+min(128, match.end()-i), row[i]))
        start = match.end()
    for i in range(start, len(row), 128):
        run = row[i:i+128]
        result.append(len(run)-1)
        result.extend(run)
    return result


class Bank:
    def __init__(self):
        self.data = bytearray()
        self.groups = []

    def score_group(self, name, images):
        # All steps in a group share one RGBA palette. Transparent gaps reveal
        # the actual cell plate, including the active column and beat markers.
        frames = [im.resize((im.width//4, im.height//4), Image.Resampling.LANCZOS)
                  for im in images]
        w, h = frames[0].size
        columns = min(16, len(frames))
        atlas = Image.new('RGBA', (columns*w, ((len(frames)+columns-1)//columns)*h))
        for i, frame in enumerate(frames):
            if frame.size != (w, h):
                raise ValueError(f'{name} frame size changed')
            atlas.paste(frame, (i%columns*w, i//columns*h))
        indexed = atlas.quantize(colors=256, method=Image.Quantize.FASTOCTREE,
                                 dither=Image.Dither.NONE)
        palette = len(self.data)
        rgba = indexed.getpalette('RGBA')
        for r, g, b, a in zip(rgba[::4], rgba[1::4], rgba[2::4], rgba[3::4]):
            self.data.extend(struct.pack('<I', a<<24 | r<<16 | g<<8 | b))
        offsets = []
        for i in range(len(frames)):
            x, y = i%columns*w, i//columns*h
            offsets.append(len(self.data))
            self.write_rows(indexed.crop((x, y, x+w, y+h)))
        self.groups.append((name, (w, h), offsets, palette))

    def write_rows(self, indexed):
        samples = indexed.tobytes()
        for i in range(0, len(samples), indexed.width):
            self.data.extend(pack_row(samples[i:i+indexed.width]))
        while len(self.data)%4:
            self.data.append(0)

    def group(self, name, images):
        offsets = []
        for image in images:
            if offsets and size != image.size:
                raise ValueError(f'{name} frame size changed')
            size = image.size
            offsets.append(len(self.data))
            if name=='backdrop':
                opaque=image.convert('RGBA');opaque.putalpha(255)
                self.data.extend(opaque.tobytes('raw','BGRA'))
                continue
            pal = image.convert('RGB').quantize(colors=256, dither=Image.Dither.NONE)
            rgb = bytes(pal.getpalette()).ljust(768, b'\0')
            self.data += b''.join(struct.pack('<I', 0xff000000 | r<<16 | g<<8 | b)
                                  for r,g,b in zip(rgb[::3], rgb[1::3], rgb[2::3]))
            self.write_rows(pal)
        self.groups.append((name, size, offsets, 0))

    def write(self):
        header = ['// Generated by tools/sp16_thorn/bake_native.py', '#pragma once',
                  'namespace tbmpc::thorn {', 'struct Images { int w, h, count; const unsigned* offsets; unsigned paletteOffset; };']
        for name, (w,h), offsets, palette in self.groups:
            header.append(f'inline constexpr unsigned {name}Offsets[] = {{')
            for i in range(0,len(offsets),12):
                header.append('    '+', '.join(map(str,offsets[i:i+12]))+',')
            header += ['};', f'inline constexpr Images {name} {{{w}, {h}, {len(offsets)}, {name}Offsets, {palette}}};']
        (DEST/'index.h').write_text('\n'.join(header+['}'])+'\n')
        (DEST/'panel.bank').write_bytes(self.data)


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--chromium', help='Optional Chromium executable')
    options = args.parse_args()
    bank = Bank()
    with tempfile.TemporaryDirectory() as folder, sync_playwright() as pw:
        page_path=Path(folder)/'study.html'
        page_path.write_text('<meta charset="utf-8">'+build_fragment())
        browser=pw.chromium.launch(executable_path=options.chromium,
                                   args=['--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
        page=browser.new_page(reduced_motion='reduce')
        page.add_init_script('window.captureThornPlates = api => window.plates = api;')
        page.goto(page_path.as_uri())
        page.wait_for_selector('#thorn-crown-metal[data-ready=true]')
        page.add_script_tag(path=SOURCE/'native-plates.js')
        def grab(kind, index=0):
            data=page.evaluate('([kind, index]) => nativePlate(kind, index)', [kind,index])
            return Image.open(io.BytesIO(base64.b64decode(data))).convert('RGBA')
        backdrop=grab('backdrop',0)
        bank.group('backdrop',[backdrop])
        for name,count in [('selected',1),('button',4),('counter',33),
                           ('number',32),('pitch',513),('pitchSelected',513),('face',33),('storm',240)]:
            frames = (grab(name,i) for i in range(count))
            if name in ('number', 'pitch', 'pitchSelected'):
                bank.score_group(name, frames)
            else:
                bank.group(name, frames)
        labels = [grab('bankLabel', i) for i in range(6)]
        titles = [grab('plotTitle', i) for i in range(5)]
        # Keep the screen plate visible outside the two chamfered corners.
        w,h=332,90
        mask=Image.new('L',(w*4,h*4))
        ImageDraw.Draw(mask).polygon([(0,0),((w-7)*4,0),(w*4,7*4),(w*4,h*4),
                                      (7*4,h*4),(0,(h-7)*4)],fill=255)
        mask=mask.resize((w,h),Image.Resampling.LANCZOS)
        corner=backdrop.crop((186,6,518,96)).convert('RGB')
        bank.group('crest',(Image.composite(grab('crest', i).convert('RGB'),corner,mask)
                            for i in range(600)))
        browser.close()
    bank.score_group('bankLabel', labels)
    bank.score_group('plotTitle', titles)
    bank.write()


if __name__=='__main__':
    main()
