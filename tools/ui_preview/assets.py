"""Rebuild the embedded type, native ribbon mark and panel-sized direction studies."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'assets/art'
EXPLORE = ROOT / 'assets/explore'
FONTS = ROOT / 'assets/fonts'
UI = ROOT / 'src/ui'


def mask(font, size, xy, text, stroke=0):
    im = Image.new('L', size)
    ImageDraw.Draw(im).text(xy, text, font=font, fill=255, stroke_width=stroke)
    return im.point(lambda v: 255 if v >= 90 else 0)


def row_bits(im):
    return '{' + ','.join(hex(sum(1 << x for x in range(im.width) if im.getpixel((x, y))))
                          for y in range(im.height)) + '}'


def put(path, lines):
    path.write_text('\n'.join(lines) + '\n')


body = ImageFont.truetype(str(FONTS/'DepartureMono-Regular.otf'), 11)
header = ['// Generated by tools/ui_preview/assets.py. OFL licences in licenses/.',
          '#pragma once', '#include <cstdint>']
glyphs = [row_bits(mask(body, (7, 12), (0, -3), chr(i) if i != 127 else '·')) for i in range(32,128)]
# A four-pixel-wide companion for note spelling in sixteen fixed columns.
# Keep the original vertical sampling (eight capital pixels).
note_chars = '0123456789ABCDEFG#-'
notes = []
for ch in note_chars:
    native = mask(body, (7, 12), (0,-3), ch)
    compact = native.crop((0,0,6,8)).resize((4,8),Image.Resampling.BOX)
    notes.append(row_bits(compact.point(lambda v: 255 if v >= 85 else 0)))
put(UI/'font.h', header + ['namespace hdui::font {', 'constexpr int glyphWidth = 7, glyphHeight = 12;',
    'inline constexpr uint8_t glyphs[][12] = {', ',\n'.join(glyphs), '};', 'inline constexpr char noteChars[] = \"' + note_chars + '\";',
    'inline constexpr uint8_t notes[][8] = {', ',\n'.join(notes), '};', '}'])

face = ImageFont.truetype(str(FONTS/'Michroma-Regular.ttf'), 26)
hex_digits = []
for ch in '0123456789ABCDEF':
    ink = mask(face, (36, 26), (2, -9), ch, 1)
    left, _, right, _ = ink.getbbox()
    digit = Image.new('L', (32, 26))
    digit.paste(ink.crop((left, 0, right, 26)), ((32-right+left)//2, 0))
    hex_digits.append(row_bits(digit))

word_font = ImageFont.truetype(str(FONTS/'Michroma-Regular.ttf'), 12)
word = mask(word_font, (124, 13), (0,-4), 'TB-MPC-3-P-0')
word = word.crop(word.getbbox())
word_rows = ['{' + ','.join(str(int(bool(word.getpixel((x, y))))) for x in range(word.width)) + '}'
             for y in range(word.height)]

# Reduce the generated original by area first, then snap faces to four inks.
raw = Image.open(EXPLORE/'ribbon-original.png').convert('RGB')
crop = raw.convert('L').point(lambda v: 255 if v > 42 else 0).getbbox()
small = raw.crop(crop).resize((28, 11), Image.Resampling.BOX)
source = [(0,0,0), (226,249,133), (74,105,38), (161,193,139)]
palette = [(10,15,13), (212,223,156), (85,105,66), (151,176,141)]
mark = Image.new('P',small.size)
mark.putpalette([v for rgb in palette for v in rgb])
mark.putdata([min(range(4), key=lambda i: sum((p-q)**2 for p,q in zip(rgb,source[i])))
              for rgb in (small.getpixel((x,y)) for y in range(small.height) for x in range(small.width))])
# Hand-clean the corner and close a one-pixel nick in the rising face.
mark.putpixel((27,0),3)
mark.putpixel((14,9),2)
mark.save(ART/'fold.png')
mark = Image.open(ART/'fold.png')
rows = ['{' + ','.join(str(mark.getpixel((x,y))) for x in range(mark.width)) + '}'
        for y in range(mark.height)]
put(UI/'identity.h', header + ['namespace hdui::art {', 'inline constexpr uint32_t hexDigits[][26] = {',
    ',\n'.join(hex_digits), '};', f'inline constexpr uint8_t wordmark[][{word.width}] = {{',
    ',\n'.join(word_rows), '};', 'inline constexpr uint8_t fold[][28] = {', ',\n'.join(rows), '};',
    'inline constexpr uint32_t inks[] = {' + ','.join(f'0xff{r:02x}{g:02x}{b:02x}' for r,g,b in palette) + '};', '}'])

# Replace the imagined soft keys with the host's actual soft-key row.
chrome = Image.open(ROOT/'tools/ui_preview/edit-keys.png').convert('RGB')
for name, top in [('folio', 71), ('ledger', 80), ('matrix', 68)]:
    im = Image.open(EXPLORE/(name+'-original.png')).convert('RGB')
    page = im.crop((0, top, im.width, im.height)).resize((320,218), Image.Resampling.LANCZOS)
    screen = Image.new('RGB',(320,240))
    screen.paste(chrome,(0,0))
    screen.paste(page,(0,22))
    screen.save(EXPLORE/(name+'-320.png'))
