"""Build the native display glyphs and indexed screen artwork."""
from foil import inlay
from math import cos, radians, sin
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'assets/art'
EXPLORE = ROOT / 'assets/explore'
FONTS = ROOT / 'assets/fonts'
UI = ROOT / 'src/ui'
header = ['// Generated by tools/ui_preview/assets.py. Font licences in licenses/.',
          '#pragma once', '#include <cstdint>']


def mask(font, size, xy, text):
    im = Image.new('L', size)
    ImageDraw.Draw(im).text(xy, text, font=font, fill=255)
    return im.point(lambda v: 255 if v >= 90 else 0)


def row_bits(im):
    return '{' + ','.join(hex(sum(1 << x for x in range(im.width) if im.getpixel((x, y))))
                          for y in range(im.height)) + '}'


def put(path, lines):
    path.write_text('\n'.join(lines) + '\n')


body_face = ImageFont.truetype(str(FONTS/'DepartureMono-Regular.otf'), 11)
glyphs, small_caps = [], []
for i in range(32,128):
    cell = mask(body_face, (7,12), (0,-3), chr(i) if i != 127 else '·')
    slim = cell.crop((0,0,6,12)).resize((5,12),Image.Resampling.BOX)
    small_caps.append(row_bits(slim.crop((0,0,5,8)).resize((5,6), Image.Resampling.BOX).point(lambda v: 255 if v >= 85 else 0)))
    glyphs.append(row_bits(slim.point(lambda v: 255 if v >= 85 else 0)))
note_chars = '0123456789ABCDEFG#-'
notes = []
for ch in note_chars:
    native = mask(body_face, (7, 12), (0,-3), ch)
    compact = native.crop((0,0,6,8)).resize((4,8),Image.Resampling.BOX)
    notes.append(row_bits(compact.point(lambda v: 255 if v >= 85 else 0)))
put(UI/'font.h', header + ['namespace hdui::font {', 'constexpr int glyphWidth = 6, glyphHeight = 12;',
    'inline constexpr uint8_t glyphs[][12] = {', ',\n'.join(glyphs), '};', 'inline constexpr char noteChars[] = "' + note_chars + '";',
    'inline constexpr uint8_t smallCaps[][6] = {', ',\n'.join(small_caps), '};', 'inline constexpr uint8_t notes[][8] = {', ',\n'.join(notes), '};', '}'])


def table(name, rows, kind='uint8_t'):
    return [f'inline constexpr {kind} {name}[][{len(rows[0])}] = {{',
            ',\n'.join('    {' + ','.join(hex(v) for v in row) + '}' for row in rows), '};']


def outline(font, text, size):
    l,t,r,b = font.getbbox(text)
    glyph = Image.new('L', (r-l,b-t))
    ImageDraw.Draw(glyph).text((-l,-t), text, font=font, fill=255)
    return glyph.resize(size, Image.Resampling.LANCZOS).point(lambda v: 255 if v >= 95 else 0)


def bits(image):
    return [[sum(1 << bit for bit in range(8) if x+bit < image.width and image.getpixel((x+bit,y)))
             for x in range(0,image.width,8)] for y in range(image.height)]


def native_plate(source, height):
    raw = source.resize((round(source.width*height/source.height), height), Image.Resampling.LANCZOS)
    cut = round(raw.width*.29)
    end = 320 - raw.width + cut
    output = Image.new('RGB', (320,height))
    output.paste(raw.crop((0,0,cut,height)))
    output.paste(raw.crop((cut,0,cut+1,height)).resize((end-cut,height)), (cut,0))
    output.paste(raw.crop((cut,0,raw.width,height)), (end,0))
    return output


def press_atlas(filename):
    source = Image.open(EXPLORE/'press-plate'/filename).convert('RGB')
    plates = Image.new('RGB', (320,106))
    plates.paste(native_plate(source, 64))
    plates.paste(native_plate(source, 42), (0,64))
    return plates.quantize(colors=128, dither=Image.Dither.NONE)


def glaze(base, finish, usable_light):
    base_palette = bytes(base.getpalette())
    offset = len(base_palette) // 3
    # Keep the expression, outlines and their antialiased edges in the original ink.
    fill = {i for (r, g, b), i in base.palette.colors.items()
            if r >= 180 and g >= 230 and b < 32}
    lit = {i for color, i in finish.palette.colors.items() if usable_light(*color)}
    indices = bytes(offset + light if ink in fill and light in lit else ink
                    for ink, light in zip(base.tobytes(), finish.tobytes()))
    result = Image.frombytes('P', base.size, indices)
    result.putpalette(base_palette + bytes(finish.getpalette()))
    return result


atlas = glaze(press_atlas('master.png'), press_atlas('jelly-finish.png'),
              lambda r, g, b: r > 120 and g > 170 and g >= r - 12 and g > b)
atlas = inlay(atlas)
palette = bytes(atlas.getpalette())
inks = ['0xff'+palette[i:i+3].hex() for i in range(0,len(palette),3)]
contents = header + ['namespace hdui::art {', 'inline constexpr uint32_t palette[] = {' + ','.join(inks) + '};']
for name, start, stop in [('hero',0,64),('editor',64,106)]:
    im = atlas.crop((0,start,320,stop))
    im.save(ART/f'press-{name}.png', optimize=True)
    data = im.tobytes()
    contents += table(name, [data[i:i+320] for i in range(0,len(data),320)])

bold = ImageFont.truetype(str(FONTS/'BarlowCondensed-BoldItalic.ttf'), 72)
digits = []
for ch in '0123456789ABCDEF':
    canvas = Image.new('L',(20,27))
    width = 14 if ch == '1' else 19
    canvas.paste(outline(bold,ch,(width,27)),((20-width)//2,0))
    digits.extend(bits(canvas))
contents += table('digits', digits)
for name, size, width, height, baseline in [('reading',18,16,19,14), ('lead',23,24,23,18)]:
    font = ImageFont.truetype(str(FONTS/'BarlowCondensed-BoldItalic.ttf'), size)
    rows, advances = [], []
    for i in range(32,127):
        ch = chr(i)
        cell = Image.new('L',(width,height))
        ImageDraw.Draw(cell).text((1,baseline), ch, font=font, fill=255, anchor='ls')
        rows.append([sum(1<<x for x in range(width) if cell.getpixel((x,y)) >= 95) for y in range(height)])
        advances.append(max(3,round(font.getlength(ch))))
    contents += table(name, rows,'uint16_t' if width <= 16 else 'uint32_t')
    contents += [f'inline constexpr uint8_t {name}Advance[] = {{' + ','.join(map(str,advances)) + '};']
# Unit directions in 1/64 pixels for a 270-degree hardware dial.
angles = [radians(135 + 270*i/48) for i in range(49)]
contents += table('dial', [(round(64*cos(a)),round(64*sin(a))) for a in angles], 'int8_t')
put(UI/'identity.h', contents + ['}'])

source = Image.open(EXPLORE/'blacklight/master.png').convert('RGB')
sticker = source.resize((77,96), Image.Resampling.LANCZOS).quantize(colors=128,dither=Image.Dither.NONE)
# The corner marks belong to the printed ticket, outside the domed face.
finish = Image.open(EXPLORE/'blacklight/jelly-finish.png').convert('RGB').resize(sticker.size, Image.Resampling.LANCZOS)
for corner in [(0, 0, 18, 19), (59, 0, 77, 11)]:
    finish.paste(sticker.crop(corner).convert('RGB'), corner)
sticker = glaze(sticker, finish.quantize(colors=128, dither=Image.Dither.NONE),
                lambda r, g, b: max(r, g) > 125 and min(r, g) > 60)
sticker.save(ART/'blacklight-pass.png', optimize=True)
palette = bytes(sticker.getpalette())
inks = ['0xff'+palette[i:i+3].hex() for i in range(0,len(palette),3)]
ticket = header + ['namespace hdui::blacklightArt {', 'inline constexpr uint32_t palette[] = {' + ','.join(inks) + '};']
data = sticker.tobytes()
ticket += table('sticker', [data[i:i+77] for i in range(0,len(data),77)])

# Set the five original letterforms separately so the L, I and N keep a
# native-pixel gap. Lift the midtones and put the reflections on the panel ink.
wordmark = Image.open(ART/'slink.png').convert('RGB')
navy = (9, 10, 35)
curve = [min(1, 1.2*max(0, (v-5)/250)**0.68) for v in range(256)]
wordmark = wordmark.point([round(bg + (255-bg)*v) for bg in navy for v in curve])
# Split between letters in the master so the L, I and N
# keep distinct stems after sampling to the 17-pixel-high header.
edges = (0, 332, 530, 575, 829, wordmark.width)
letters = []
for left, right in zip(edges, edges[1:]):
    letter = wordmark.crop((left, 0, right, wordmark.height))
    letters.append(letter.resize((round(letter.width*120/wordmark.width), 17), Image.Resampling.LANCZOS))
gap = 2
title = Image.new('RGB', (sum(letter.width for letter in letters) + gap*(len(letters)-1), 17), navy)
x = 0
for letter in letters:
    title.paste(letter, (x, 0))
    x += letter.width + gap
title = title.filter(ImageFilter.UnsharpMask(radius=0.75, percent=65, threshold=3))
title = title.quantize(colors=64, dither=Image.Dither.NONE)
palette = bytes(title.getpalette())
inks = ['0xff'+palette[i:i+3].hex() for i in range(0,len(palette),3)]
ticket += ['inline constexpr uint32_t titlePalette[] = {' + ','.join(inks) + '};']
data = title.tobytes()
ticket += table('title', [data[i:i+title.width] for i in range(0,len(data),title.width)])

put(UI/'blacklight_art.h', ticket + ['}'])
