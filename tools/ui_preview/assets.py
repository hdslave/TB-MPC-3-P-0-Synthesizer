"""Build the native display glyphs, indexed artwork and 320-pixel direction studies."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'assets/art'
EXPLORE = ROOT / 'assets/explore'
ACID = EXPLORE / 'acid'
FONTS = ROOT / 'assets/fonts'
UI = ROOT / 'src/ui'
header = ['// Generated by tools/ui_preview/assets.py. Font licences in licenses/.',
          '#pragma once', '#include <cstdint>']


def mask(font, size, xy, text):
    im = Image.new('L', size)
    ImageDraw.Draw(im).text(xy, text, font=font, fill=255)
    return im.point(lambda v: 255 if v >= 90 else 0)


def row_bits(im):
    return '{' + ','.join(hex(sum(1 << x for x in range(im.width) if im.getpixel((x, y))))
                          for y in range(im.height)) + '}'


def put(path, lines):
    path.write_text('\n'.join(lines) + '\n')


body_face = ImageFont.truetype(str(FONTS/'DepartureMono-Regular.otf'), 11)
glyphs = [row_bits(mask(body_face, (7, 12), (0, -3), chr(i) if i != 127 else '·')) for i in range(32,128)]
note_chars = '0123456789ABCDEFG#-'
notes = []
for ch in note_chars:
    native = mask(body_face, (7, 12), (0,-3), ch)
    compact = native.crop((0,0,6,8)).resize((4,8),Image.Resampling.BOX)
    notes.append(row_bits(compact.point(lambda v: 255 if v >= 85 else 0)))
put(UI/'font.h', header + ['namespace hdui::font {', 'constexpr int glyphWidth = 7, glyphHeight = 12;',
    'inline constexpr uint8_t glyphs[][12] = {', ',\n'.join(glyphs), '};', 'inline constexpr char noteChars[] = "' + note_chars + '";',
    'inline constexpr uint8_t notes[][8] = {', ',\n'.join(notes), '};', '}'])

# All production art is a one-bit ink mask. Keep a two-ink PNG of each native plate.
inks = [(215,241,67), (12,14,16)]


def plate(mask, name):
    assert mask.width % 8 == 0
    proof = Image.new('P',mask.size)
    proof.putpalette([component for ink in inks for component in ink])
    proof.putdata([bool(v) for v in mask.tobytes()])
    proof.save(ART/(name+'.png'))
    rows = []
    for y in range(mask.height):
        values = []
        for x in range(0,mask.width,8):
            word = sum(1 << bit for bit in range(8) if mask.getpixel((x+bit,y)))
            values.append(f'0x{word:02x}')
        rows.append('    {' + ','.join(values) + '}')
    return [f'inline constexpr uint8_t {name}[][{mask.width//8}] = {{', ',\n'.join(rows), '};']


original = Image.open(ACID/'orbit-original.png').convert('L')


def orbit(size):
    # Area sampling holds the very narrow notches and the hole in the tilted loop.
    return original.resize(size,Image.Resampling.BOX).point(lambda p: 255 if p < 113 else 0)


# Draw exactly four fixed-width digits. Set a common cap height and baseline.
face = ImageFont.truetype(str(FONTS/'Michroma-Regular.ttf'), 88)
atlas = Image.new('L',(24,16*25))
for i,ch in enumerate('0123456789ABCDEF'):
    im = Image.new('L',(140,130))
    ImageDraw.Draw(im).text((8,-20),ch,font=face,fill=255,stroke_width=2,stroke_fill=255)
    im = im.crop(im.getbbox())
    width = max(6,min(22,round(im.width * 22/100)))
    glyph = im.resize((width,23),Image.Resampling.LANCZOS).point(lambda p: 255 if p>=110 else 0)
    atlas.paste(glyph,((24-width)//2,25*i+1))

# Preserve a full eight-pixel body cap in the small instrument signature.
titles = Image.new('L',(80,13*5))
for i,ch in enumerate('TB-MPC-3-P-0'):
    native = mask(body_face,(7,12),(0,-3),ch)
    titles.paste(native.crop((0,0,6,8)),(i*6,0))
title_face = ImageFont.truetype(str(FONTS/'Michroma-Regular.ttf'),44)
for i,name in enumerate(('VOICE','TONE','TB-3PO','CLOCK'),1):
    title = Image.new('L',(440,80))
    ImageDraw.Draw(title).text((4,-10),name,font=title_face,fill=255,stroke_width=1,stroke_fill=255)
    title = title.crop(title.getbbox())
    width = min(76,round(title.width*10/title.height))
    title = title.resize((width,10),Image.Resampling.LANCZOS).point(lambda p: 255 if p>=110 else 0)
    titles.paste(title,(0,i*13+1))

put(UI/'identity.h', header + ['namespace hdui::art {']
    + plate(orbit((96,55)),'orbit') + plate(orbit((48,27)),'stamp')
    + plate(atlas,'digits') + plate(titles,'titles') + ['}'])

chrome = Image.open(ROOT/'tools/ui_preview/edit-keys.png').convert('RGB')
for name, top in [('kernel', 55), ('ripple', 66), ('shard', 65)]:
    im = Image.open(ACID/(name+'-original.png')).convert('RGB')
    screen = Image.new('RGB',(320,240))
    screen.paste(chrome,(0,0))
    screen.paste(im.crop((0,top,im.width,im.height)).resize((320,218),Image.Resampling.LANCZOS),(0,22))
    screen.save(ACID/(name+'-320.png'))
