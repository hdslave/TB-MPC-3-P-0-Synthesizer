"""Bake the Press Plate nameplate and smoothly indexed satin dials at MPC resolution."""
from math import cos, radians, sin
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'assets/art'
AA = 8
METAL = '#cdcfd6'


def nameplate():
    width, height = 224, 30
    plate = Image.new('RGB', (width, height))
    draw = ImageDraw.Draw(plate)
    for y in range(height):
        level = round(216 - 13 * y / height) + (0, 1, -1, 0)[y % 4]
        draw.line((0, y, width - 1, y), fill=(level, level + 2, level + 8))
    draw.line((0, 28, width - 1, 28), fill='#edf0fa')
    draw.line((0, 29, width - 1, 29), fill='#273661')

    logo = Image.open(ART / 'slink.png').convert('RGB')
    red, green, blue = logo.split()
    alpha = ImageChops.lighter(ImageChops.lighter(red, green), blue)
    logo.putalpha(alpha.point(lambda v: max(0, min(255, (v - 5) * 255 / 13))))
    logo = logo.crop(logo.getbbox())
    logo.thumbnail((180, 26), Image.Resampling.LANCZOS)
    plate.paste(logo, (118 - logo.width // 2, 2), logo)
    return plate


def dial_frames():
    size = 23
    centre = size * AA // 2
    face = Image.open(ART / 'satin-knob.png').convert('RGBA').resize((18*AA, round(18.6*AA)), Image.Resampling.LANCZOS)
    base = Image.new('RGB', (size*AA, size*AA), METAL)
    shadow = Image.new('L', base.size)
    ImageDraw.Draw(shadow).ellipse((2*AA, 3*AA, 21*AA, 22*AA), fill=120)
    base.paste('#182335', (0, 0, *base.size), shadow.filter(ImageFilter.GaussianBlur(0.8*AA)))
    radius = 10.9*AA
    ring = tuple(round(centre + r) for r in (-radius, -radius, radius, radius))

    def point(angle, radius):
        theta = radians(angle)
        return (round(centre + AA*radius*cos(theta)), round(centre + AA*radius*sin(theta)))

    frames = []
    for index in range(49):
        angle = 135 + 270 * index / 48
        dial = base.copy()
        draw = ImageDraw.Draw(dial)
        draw.arc(ring, 135, 405, fill='#354155', width=round(1.65*AA))
        draw.arc(ring, 135, angle, fill='#374ad1', width=round(1.65*AA))
        dial.paste(face, (centre - face.width//2, centre - face.height//2), face)
        draw.line([point(angle, 2.15), point(angle, 7.65)], fill='#18283f', width=round(2.05*AA))
        draw.line([point(angle, 2.5), point(angle, 7.45)], fill='#eef8ff', width=round(1.35*AA))
        frames.append(dial.resize((size, size), Image.Resampling.LANCZOS))
    return frames


def table(name, rows, kind='uint8_t'):
    return [f'inline constexpr {kind} {name}[][{len(rows[0])}] = {{',
            ',\n'.join('    {' + ','.join(map(str, row)) + '}' for row in rows), '};']


plate = nameplate()
dials = dial_frames()
atlas = Image.new('RGB', (plate.width, plate.height + ((len(dials)+8)//9)*23), METAL)
atlas.paste(plate)
for i, dial in enumerate(dials):
    atlas.paste(dial, ((i%9)*23, plate.height + (i//9)*23))
atlas = atlas.quantize(colors=256, dither=Image.Dither.NONE)
palette = bytes(atlas.getpalette())
inks = ['0xff'+palette[i:i+3].hex() for i in range(0, len(palette), 3)]
header = ['// Generated by tools/ui_preview/silver.py.', '#pragma once', '#include <cstdint>',
          'namespace hdui::silver {', f'inline constexpr uint32_t cardMetal = 0xff{METAL[1:]};',
          'inline constexpr uint32_t palette[] = {' + ','.join(inks) + '};']
header += table('plate', [atlas.crop((0,y,plate.width,y+1)).tobytes() for y in range(plate.height)])

# Most scanlines are identical across pointer positions. Store each distinct row once.
rows, indices = {}, []
for i, dial in enumerate(dials):
    x, y = (i%9)*23, plate.height + (i//9)*23
    indices.append([])
    for dy in range(dial.height):
        row = atlas.crop((x, y+dy, x+dial.width, y+dy+1)).tobytes()
        indices[-1].append(rows.setdefault(row, len(rows)))
header += table('dialRows', list(rows)) + table('dial', indices, 'uint16_t') + ['}']
(ROOT / 'src/ui/silver_art.h').write_text('\n'.join(header) + '\n')
