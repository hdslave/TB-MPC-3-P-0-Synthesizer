"""Bake Press Plate's native-size type. Each pixel retains eight levels of coverage."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / 'assets/fonts'
out = ['// Generated by tools/ui_preview/press_type.py.', '#pragma once', '#include <cstdint>',
       'namespace hdui::pressType {',
       'struct Face { const uint64_t* rows; const uint8_t* advance; int height; };']


def scanlines(mask):
    assert mask.width <= 21
    return [hex(sum(((mask.getpixel((x, y))*7+127)//255) << (3*x) for x in range(mask.width)))
            for y in range(mask.height)]


def face(name, size, height, baseline):
    font = ImageFont.truetype(str(FONTS / 'Barlow-SemiBold.ttf'), size)
    glyphs, advances = [], []
    for code in range(32, 127):
        ch = chr(code)
        left, _, right, _ = font.getbbox(ch, anchor='ls')
        offset = max(0, -left)
        advance = max(1, round(font.getlength(ch)), offset+right)
        glyph = Image.new('L', (advance, height))
        ImageDraw.Draw(glyph).text((offset, baseline), ch, font=font, fill=255, anchor='ls')
        glyphs.append(','.join(scanlines(glyph)))
        advances.append(str(advance))
    out.extend([f'inline constexpr uint64_t {name}Rows[] = {{', ',\n'.join(glyphs), '};',
                f'inline constexpr uint8_t {name}Advance[] = {{' + ','.join(advances) + '};',
                f'inline constexpr Face {name} {{ {name}Rows, {name}Advance, {height} }};'])


face('label', 11, 12, 8)
face('caption', 10, 11, 8)
face('compact', 9, 9, 7)
face('value', 16, 19, 13)
face('lead', 20, 23, 16)

# Long accidentals and negative octaves must still fit a single matrix cell.
note_font = ImageFont.truetype(str(FONTS / 'Barlow-SemiBold.ttf'), 24)
notes = []
for ch in '0123456789ABCDEFG#-':
    left, _, right, _ = note_font.getbbox(ch, anchor='ls')
    glyph = Image.new('L', (right-left, 18))
    ImageDraw.Draw(glyph).text((-left, 18), ch, font=note_font, fill=255, anchor='ls')
    notes.append('{' + ','.join(scanlines(glyph.resize((4, 8), Image.Resampling.LANCZOS))) + '}')
out.extend(['inline constexpr uint64_t notes[][8] = {', ',\n'.join(notes), '};'])

# Retain the four fixed seed cells and the original italic numeral silhouettes.
seed_font = ImageFont.truetype(str(FONTS / 'BarlowCondensed-BoldItalic.ttf'), 72)
seed = []
for ch in '0123456789ABCDEF':
    l, t, r, b = seed_font.getbbox(ch)
    source = Image.new('L', (r-l, b-t))
    ImageDraw.Draw(source).text((-l, -t), ch, font=seed_font, fill=255)
    w = 14 if ch == '1' else 19
    cell = Image.new('L', (20, 27))
    cell.paste(source.resize((w, 27), Image.Resampling.LANCZOS), ((20-w)//2, 0))
    seed.append('{' + ','.join(scanlines(cell)) + '}')
out.extend(['inline constexpr uint64_t seed[][27] = {', ',\n'.join(seed), '};', '}'])
(ROOT / 'src/ui/press_type.h').write_text('\n'.join(out) + '\n')
